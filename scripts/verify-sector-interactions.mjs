import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { createJiti } from 'jiti'
const jiti = createJiti(import.meta.url, { alias: { '~': fileURLToPath(new URL('../app', import.meta.url)) } })
const { useDemoChoice } = await jiti.import('../app/composables/useDemoChoice.ts')
const data = await jiti.import('../app/constants/sectorDemos.ts')
for (const [name, choices] of Object.entries(data)) {
 const state = useDemoChoice(choices)
 for (let i = 0; i < choices.length; i++) {
  state.choose(i)
  assert.equal(state.current.value.name, choices[i].name, name)
 }
 const last = state.current.value.name
 state.choose(-1)
 state.choose(choices.length)
 state.choose(1.5)
 assert.equal(state.current.value.name, last, `${name}: invalid selection must preserve state`)
 state.choose(0)
 assert.equal(state.current.value.name, choices[0].name)
}
const { useIndustrialComparison } = await jiti.import('../app/composables/useIndustrialComparison.ts')
const comparison = useIndustrialComparison()
assert.equal(comparison.first.value.model, 'GDR')
comparison.firstId.value = 'a10'
comparison.secondId.value = '21353'
assert.equal(comparison.first.value.model, 'A-10')
assert.equal(comparison.second.value.model, '213.53')
assert.ok(comparison.rows.value.some(row => row.label === 'Proteção' && row.first === 'Consultar ficha' && row.second === 'IP65'))
console.log('All sector selections and industrial comparison passed.')

const { useDemoQuoteList } = await jiti.import('../app/composables/useDemoQuoteList.ts')
const quoteList = useDemoQuoteList()
quoteList.add(); quoteList.add()
assert.equal(quoteList.items.value.length, 1)
assert.equal(quoteList.items.value[0].quantity, 2)
quoteList.productId.value = 'a10'; quoteList.add()
assert.equal(quoteList.items.value.length, 2)
quoteList.change('a10', -1)
assert.equal(quoteList.items.value.length, 1)
quoteList.change('gdr', 5000)
assert.equal(quoteList.items.value[0].quantity, 999)
quoteList.clear()
assert.equal(quoteList.items.value.length, 0)
quoteList.productId.value = 'missing'; quoteList.add()
assert.equal(quoteList.items.value.length, 0)
const { useDemoWorkshop } = await jiti.import('../app/composables/useDemoWorkshop.ts')
const history = useDemoWorkshop()
history.add()
assert.ok(history.error.value)
assert.equal(history.ordered.value.length, 0)
history.date.value = '2026-08-01'; history.km.value = '10000'; history.service.value = 'Troca de óleo'; history.add()
assert.equal(history.error.value, '')
history.date.value = '2026-07-01'; history.km.value = '9000'; history.service.value = 'Inspeção'; history.add()
assert.equal(history.ordered.value[0].date, '2026-08-01')
history.km.value = '-1'; history.service.value = 'Inválido'; history.add()
assert.equal(history.ordered.value.length, 2)
history.remove(history.ordered.value[0].id)
assert.equal(history.ordered.value.length, 1)
console.log('Quote list and vehicle history passed.')

const { usePhotoPortfolio } = await jiti.import('../app/composables/usePhotoPortfolio.ts')
const photos = usePhotoPortfolio()
assert.equal(photos.visible.value.length, 6)
photos.onlyFavorites.value = true
assert.equal(photos.visible.value.length, 0)
photos.toggle('01'); photos.toggle('03')
assert.equal(photos.visible.value.length, 2)
photos.category.value = 'Retratos'
assert.deepEqual(photos.visible.value.map(p => p.id), ['01'])
photos.toggle('01')
assert.equal(photos.visible.value.length, 0)
photos.reset()
assert.equal(photos.visible.value.length, 6)
photos.selectedId.value = '01'; photos.move(-1)
assert.equal(photos.selectedId.value, '06')
photos.move(1)
assert.equal(photos.selectedId.value, '01')
photos.category.value = 'Retratos'; photos.move(1)
assert.equal(photos.selectedId.value, '04')
photos.move(1)
assert.equal(photos.selectedId.value, '01')
photos.toggle('invalid')
assert.ok(!photos.favorites.value.includes('invalid'))
console.log('Photography filtering, favorites and gallery navigation passed.')
