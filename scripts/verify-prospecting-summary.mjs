import assert from 'node:assert/strict'
import { createJiti } from 'jiti'
const jiti=createJiti(import.meta.url,{alias:{'~':`${process.cwd()}/app`}})
const {newProspect,getLeadContactStatus}=await jiti.import('../app/utils/prospecting.ts')
const {outreachSummary}=await jiti.import('../app/utils/prospecting-summary.ts')
const event=stage=>({id:crypto.randomUUID(),date:'2026-10-01',channel:'WhatsApp',stage,note:'Registro antigo'})
const lead=(status,extra={})=>({...newProspect(),contactStatus:status,history:[event('Contatado'),event('Respondeu')],...extra})
const untouched=Array.from({length:14},()=>lead('Nenhum contato'))
assert.equal(outreachSummary(untouched,30).contacted,0)
assert.equal(outreachSummary(untouched,30).responses,0)
assert.equal(outreachSummary(untouched,30).notContacted,14)
const leads=[lead('Nenhum contato'),lead('Contato realizado'),lead('Não atendeu'),lead('Não respondeu'),lead('Contato realizado',{archived:true})]
let result=outreachSummary(leads,30)
assert.equal(result.responses,1);assert.equal(result.contacted,1)
assert.equal(result.noAnswer,1);assert.equal(result.noReply,1)
assert.equal(result.notContacted,1);assert.equal(result.attempted,3)
assert.equal(result.remaining,29)
for(const [status,key] of [['Nenhum contato','notContacted'],['Contato realizado','responses'],['Não atendeu','noAnswer'],['Não respondeu','noReply']]) assert.equal(result[key],leads.filter(l=>!l.archived&&getLeadContactStatus(l)===status).length)
leads[1].contactStatus='Nenhum contato'
assert.equal(outreachSummary(leads,30).responses,0)
const answered=Array.from({length:30},()=>lead('Contato realizado',{history:[]}))
assert.equal(outreachSummary(answered,30).reached,true)
assert.equal(outreachSummary(answered,40).remaining,10)
assert.equal(outreachSummary(answered,50).remaining,20)
assert.equal(outreachSummary(answered,20).progress,100)
assert.equal(outreachSummary([],30).progress,0)
// Legacy records use exactly the same fallback as the card.
const legacy=lead(undefined,{history:[event('Contatado')]})
assert.equal(outreachSummary([legacy],30).responses,getLeadContactStatus(legacy)==='Contato realizado'?1:0)
console.log('OK: todos Nenhum contato = zero, status atual prevalece sobre histórico, contadores iguais aos cards, arquivadas e metas 30/40/50.')
