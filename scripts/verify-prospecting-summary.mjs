import assert from 'node:assert/strict'
import { createJiti } from 'jiti'
const jiti=createJiti(import.meta.url,{alias:{'~':`${process.cwd()}/app`}})
const {newProspect}=await jiti.import('../app/utils/prospecting.ts')
const {outreachSummary}=await jiti.import('../app/utils/prospecting-summary.ts')
const {settingsSchema}=await jiti.import('../app/validation/prospecting.ts')
const event=stage=>({id:crypto.randomUUID(),date:'2026-10-01',channel:'WhatsApp',stage,note:'Registro'})
const lead=(history=[],extra={})=>({...newProspect(),history,...extra})
const leads=[lead(),lead([event('Contatado'),event('Contatado')]),lead([event('Contatado'),event('Respondeu'),event('Interessado')]),lead([event('Não contatar')],{stage:'Não contatar'}),lead([event('Sem interesse')],{archived:true})]
const summary=outreachSummary(leads,30)
assert.equal(summary.contacted,4)
assert.equal(summary.responses,2)
assert.equal(summary.unanswered,2)
assert.equal(summary.notContacted,1)
assert.equal(summary.remaining,28)
assert.equal(summary.reached,false)
assert.equal(summary.stages.reduce((sum,item)=>sum+item.count,0),4)
const answered=Array.from({length:30},()=>lead([event('Respondeu'),event('Respondeu')]))
assert.equal(outreachSummary(answered,30).reached,true)
assert.equal(outreachSummary(answered,30).responses,30)
assert.equal(outreachSummary(answered,30).progress,100)
assert.equal(outreachSummary(answered,40).remaining,10)
assert.equal(outreachSummary(answered,50).remaining,20)
assert.equal(outreachSummary(answered,20).remaining,0)
assert.equal(outreachSummary(answered,20).progress,100)
for(const target of [30,40,50])assert.equal(settingsSchema.safeParse({target,budget:0}).success,true)
assert.equal(outreachSummary([],30).progress,0)
console.log('OK: respostas únicas, tentativas sem resposta, não contatar, arquivadas, meta atingida e ajuste 30/40/50.')
