import assert from 'node:assert/strict'
import { createJiti } from 'jiti'
const jiti = createJiti(import.meta.url, { alias: { '~': `${process.cwd()}/app` } })
const { newProspect, heat, recordActivity, addDays, contactCounted, responseCounted, interestCounted, segmentResults, terminalStage, draftApproach } = await jiti.import('../app/utils/prospecting.ts')
const { prospectSchema, activitySchema, prospectDataSchema } = await jiti.import('../app/validation/prospecting.ts')
const { loadProspecting, persistProspecting, readProspectingBackup } = await jiti.import('../app/services/prospecting.ts')
let lead = { ...newProspect(), company: 'Empresa de teste', city: 'Osasco', segment: 'Floricultura', activity: 'Ativo', professional: true, websiteStatus: 'Sem site' }
assert.equal(prospectSchema.safeParse(lead).success, true)
assert.equal(heat(lead), 'Quente')
assert.equal(heat({ ...lead, websiteStatus: 'Site antigo ou ruim' }), 'Morno')
assert.equal(heat({ ...lead, activity: 'Aparentemente abandonado' }), 'Descartar')
assert.equal(heat({ ...lead, professional: false }), 'Revisar')
assert.equal(heat({ ...lead, heatOverride: 'Morno' }), 'Morno')
assert.equal(prospectSchema.safeParse({ ...lead, website: 'javascript:alert(1)' }).success, false)
assert.equal(prospectSchema.safeParse({ ...lead, rating: 6 }).success, false)
assert.equal(prospectSchema.safeParse({ ...lead, followUp: '2026-02-30' }).success, false)
assert.equal(addDays('2026-12-31', 2), '2027-01-02')
assert.equal(addDays('2028-02-28', 2), '2028-03-01')
const activity = { date: '2026-09-01', channel: 'WhatsApp', stage: 'Contatado', note: 'Abordagem realizada.', followUp: '2026-09-03', nextAction: 'Retomar' }
assert.equal(activitySchema.safeParse({ ...activity, followUp: '2026-08-31' }).success, false)
lead = recordActivity(lead, activity)
lead = recordActivity(lead, { ...activity, date: '2026-09-03', stage: 'Interessado', followUp: '2026-09-05' })
assert.equal(contactCounted(lead), true)
assert.equal(responseCounted(lead), true)
assert.equal(interestCounted(lead), true)
assert.equal(segmentResults([lead])[0].contacted, 1)
assert.equal(segmentResults([lead])[0].rate, 100)
const backdated = recordActivity(lead, { ...activity, date: '2026-09-02' })
assert.equal(backdated.stage, 'Interessado')
assert.equal(backdated.followUp, '2026-09-05')
const closed = recordActivity(lead, { ...activity, date: '2026-09-04', stage: 'Não contatar' })
assert.equal(closed.followUp, '')
assert.equal(closed.nextAction, '')
assert.equal(terminalStage(closed.stage), true)
assert.ok(draftApproach(lead).includes('Empresa de teste'))
const values = new Map()
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) }
assert.equal(loadProspecting().settings.budget, 0)
const data = { version: 1, leads: [lead], settings: { target: 30, budget: 150 } }
persistProspecting(data)
assert.deepEqual(loadProspecting(), data)
assert.equal(prospectDataSchema.safeParse({ ...data, leads: [lead, lead] }).success, false)
assert.throws(() => persistProspecting({ ...data, settings: { target: -1, budget: 0 } }))
assert.deepEqual(loadProspecting(), data)
assert.deepEqual(await readProspectingBackup(new File([JSON.stringify(data)], 'backup.json')), data)
await assert.rejects(readProspectingBackup(new File(['invalid'], 'backup.json')))
await assert.rejects(readProspectingBackup({ size: 10000001 }))
const base = 'http://127.0.0.1:3000'
const response = await fetch(`${base}/prospeccao`)
assert.equal(response.status, 200)
const html = await response.text()
assert.ok(html.includes('noindex, nofollow'))
assert.ok(html.includes('Boas conversas começam aqui.'))
assert.ok(!html.includes('gtag/js'))
const sitemap = await (await fetch(`${base}/sitemap.xml`)).text()
assert.ok(!sitemap.includes('/prospeccao'))
console.log('Prospecting qualification, validation, follow-ups, history, unique-company metrics, persistence, backups and route passed.')
